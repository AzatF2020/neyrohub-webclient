import { api } from './api';

/**
 * Промпт в расчёт цены не входит: стоимость складывается из опций — разрешения,
 * длительности, модели, — а текст запроса на неё не влияет. Схему модели бэкенд
 * всё равно проверяет целиком и пустой промпт не примет, поэтому подставляем точку.
 * Заодно набор параметров не меняется на каждую букву, и запрос не улетает при наборе.
 */
export const PRICE_PROMPT = '.';

/**
 * Цена одной генерации: `POST /pricing/detail` считает её по модели и опциям и
 * отдаёт в кредитах и рублях. Себестоимость наружу не выходит — её считает бэкенд.
 *
 * Ручка анонимная: ценник видно и до входа.
 */
export async function fetchPrice({ type, model, options }) {
	const { data } = await api.post('/pricing/detail', { type, model, options });

	return { credits: data.credits, priceRub: data.priceRub };
}
