/**
 * Разметка ответа модели в обычный текст — для мест, где markdown рисовать нечем и незачем:
 * превью в списке чатов, alt картинки, заголовок вкладки. Полноценный разбор для этого
 * не нужен и слишком дорог: renderMarkdown тянет за собой markdown-it, katex и highlight.js,
 * а здесь достаточно снять сами метки и оставить текст.
 */

/** Метки, которые снимаются построчно: заголовки, цитаты, списки, ограждения блоков кода */
const LINE_MARKS = [
	// ### Заголовок
	[/^\s{0,3}#{1,6}\s+/, ''],
	// > цитата, в том числе вложенная
	[/^\s{0,3}(?:>\s?)+/, ''],
	// - пункт, * пункт, 1. пункт
	[/^\s*(?:[-*+]|\d{1,9}[.)])\s+/, ''],
	// [x] в списке задач: без флажка перед ним это просто скобки
	[/^\[[ xX]]\s+/, ''],
	// ```js — ограждение блока кода: сам код в превью полезнее, чем пустота
	[/^\s{0,3}(?:`{3,}|~{3,}).*$/, ''],
];

/** Строки, от которых в тексте ничего не остаётся: --- и разделитель шапки таблицы */
const DROPPED_LINE = /^\s{0,3}(?:([-*_])\s*(?:\1\s*){2,}|\|?[\s:|-]*\|[\s:|-]*)$/;

export function toPlainText(markdown) {
	if (!markdown) return '';

	const lines = markdown
		.split('\n')
		.filter((line) => !DROPPED_LINE.test(line))
		.map((line) => {
			let text = line;
			for (const [mark, replacement] of LINE_MARKS) text = text.replace(mark, replacement);
			// Ячейки таблицы: границы становятся пробелами, чтобы строка читалась как строка
			return text.includes('|') ? text.replace(/\s*\|\s*/g, '  ').trim() : text;
		});

	return (
		lines
			.join('\n')
			// ![alt](url) → alt: сама картинка в превью не попадёт, а подпись пригодится
			.replace(/!\[([^\]]*)]\([^)]*\)/g, '$1')
			// [текст](url) и ссылка по ярлыку [текст][id] → текст
			.replace(/\[([^\]]*)]\((?:[^)]*)\)/g, '$1')
			.replace(/\[([^\]]*)]\[[^\]]*]/g, '$1')
			// <https://example.com> → https://example.com
			.replace(/<((?:https?|mailto):[^>\s]+)>/g, '$1')
			// **жирный**, __жирный__, ~~зачёркнутый~~
			.replace(/(?<!\\)(\*\*|__|~~)(?=\S)([\s\S]*?\S)\1/g, '$2')
			// *курсив* — звёздочка вплотную к тексту с обеих сторон
			.replace(/(?<![\w*\\])\*(?=\S)([^*\n]*\S)\*(?![\w*])/g, '$1')
			// _курсив_ — но не подчёркивание внутри имён вроде some_long_name
			.replace(/(?<![\w_\\])_(?=\S)([^_\n]*\S)_(?![\w_])/g, '$1')
			// `код` в строке
			.replace(/(?<!\\)`+([^`\n]+)`+/g, '$1')
			// Экранированная разметка: \* и \_ автор писал ради самих символов,
			// поэтому метки выше обходят их стороной, а слэш снимается здесь
			.replace(/\\([\\`*_{}[\]()#+\-.!>~|])/g, '$1')
			// Пустые строки от снятых меток превью только растягивают
			.replace(/[ \t]+$/gm, '')
			.replace(/\n{2,}/g, '\n')
			.trim()
	);
}
